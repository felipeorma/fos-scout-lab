export type Lang = "es" | "en";

// El español es el idioma fuente: cada texto visible se usa tal cual como
// clave. t() devuelve la clave en español o su traducción en inglés según el
// idioma activo. Los textos escritos por el usuario pasan por t() y, al no
// estar en el diccionario, se muestran sin cambios.
let currentLang: Lang = "es";

export function activeLang() {
  return currentLang;
}

export function setActiveLang(lang: Lang) {
  currentLang = lang;
}

export function numberLocale() {
  return currentLang === "es" ? "es-CL" : "en-US";
}

export function t(text: string): string {
  if (currentLang === "es") return text;
  return EN[text] ?? text;
}

